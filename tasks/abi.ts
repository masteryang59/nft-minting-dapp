// Writes the contract ABI into the frontend as a typed `as const` module, so viem infers
// function names, args and return types there without depending on Hardhat.
import { writeFile } from "node:fs/promises";
import path from "node:path";

import type { HardhatRuntimeEnvironment } from "hardhat/types/hre";

import { ROOT } from "./common.ts";

export const ABI_FILE = path.join(ROOT, "frontend", "src", "abi.ts");

export function renderAbiModule(abi: unknown): string {
  return `// Generated by \`npx hardhat moths:abi\` from contracts/LumenMoths.sol. Do not edit.\nexport const lumenMothsAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}

export default async function exportAbi(_args: unknown, hre: HardhatRuntimeEnvironment) {
  const { abi } = await hre.artifacts.readArtifact("LumenMoths");
  await writeFile(ABI_FILE, renderAbiModule(abi));
  console.log(`wrote ${path.relative(ROOT, ABI_FILE)} (${abi.length} entries)`);
}

export function invalidateCache(data: unknown): unknown {
  if (!data) return null;
  return data;
}